# POCKET METAL's fonts (firmware/apps/metal/mx_fonts.h): anti-aliased bitmaps, 4 bits a pixel, in the format of
# tools/mkfont.py (op_font, drawn by firmware/ui_text.h's ft_box). The sources are SIL Open Font License 1.1 fonts kept
# in assets/metal/fonts/ with their licences:
#   a blackletter for the names and numbers (Pirata One), a Fraktur for the titles (UnifrakturMaguntia), a condensed
#   sans for what must be read at a glance (Barlow Condensed).
# The bitmaps are made for this screen; they are not fonts and carry none of the fonts' names.
#   python3 tools/metal/mkfont_metal.py
import os
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "assets", "metal", "fonts")
OUT = os.path.join(ROOT, "firmware", "apps", "metal", "mx_fonts.h")
UP = " !#&'()*+,-./0123456789:<>?ABCDEFGHIJKLMNOPQRSTUVWXYZ%"
ASCII = "".join(chr(c) for c in range(0x20, 0x7F))
FONTS = [   # C name, file, size px, characters, extra tracking, what it is for
    ("MF_NAME", "PirataOne-Regular.ttf", 34, UP, 0, "the preset's name"),
    ("MF_NUM", "PirataOne-Regular.ttf", 62, " 0123456789", 0, "the preset's number"),
    ("MF_HEAD", "PirataOne-Regular.ttf", 24, ASCII, 0, "a block's type, a page's heading"),
    ("MF_FRAK", "UnifrakturMaguntia-Book.ttf", 30, ASCII, 0, "titles: the product, the block"),
    ("MF_NOTE", "PirataOne-Regular.ttf", 96, " ABCDEFG#-", 0, "the tuner's note"),
    ("MF_LBL", "BarlowCondensed-SemiBold.ttf", 15, ASCII, 0, "labels, values, footers"),
    ("MF_VAL", "BarlowCondensed-Bold.ttf", 21, ASCII, 0, "a setting's value, the style"),
]


def build(fname, size, chars, track):
    f = ImageFont.truetype(os.path.join(SRC, fname), size)
    top, bot = 10 ** 9, -10 ** 9
    for ch in chars:
        bb = f.getbbox(ch)
        if bb[2] > bb[0]:
            top, bot = min(top, bb[1]), max(bot, bb[3])
    H = bot - top
    glyphs = []
    for ch in chars:
        adv = int(round(f.getlength(ch))) + track
        bb = f.getbbox(ch)
        ink = bb[2] if bb[2] > bb[0] else 0
        w = max(adv, ink, 1)                      # a blackletter's swash may pass its advance: keep it whole
        im = Image.new("L", (w + 4, H), 0)
        ImageDraw.Draw(im).text((0, -top), ch, font=f, fill=255)
        im = im.crop((0, 0, w, H))
        px = [min(15, (v + 8) >> 4) for v in im.getdata()]
        if len(px) % 2:
            px.append(0)
        glyphs.append((ch, w, bytes((px[i] << 4) | px[i + 1] for i in range(0, len(px), 2))))
    return H, glyphs


def main():
    lines = ["/* GENERATED by tools/metal/mkfont_metal.py: do not edit. POCKET METAL's screen fonts, rendered from SIL Open Font",
             " * License 1.1 fonts (assets/metal/fonts: Pirata One by Rodrigo Fuenzalida and Nicolas Massi; UnifrakturMaguntia by",
             " * j. 'mach' wust and Peter Wiegel; Barlow Condensed by the Barlow Project Authors). Anti-aliased bitmaps, 4 bits a",
             " * pixel (2 pixels a byte, the high nibble on the left), for firmware/ui_text.h's ft_box. */",
             "#pragma once", ""]
    total = 0
    for name, fname, size, chars, track, what in FONTS:
        H, gl = build(fname, size, chars, track)
        bits = b"".join(g[2] for g in gl)
        offs, o = [], 0
        for g in gl:
            offs.append(o)
            o += len(g[2])
        total += len(bits)
        esc = chars.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f"/* {name}: {what}. {fname} {size} px, {H} px high, {len(gl)} characters, {len(bits)} bytes */")
        lines.append(f"static const uint8_t {name}_adv[{len(gl)}] = {{{', '.join(str(g[1]) for g in gl)}}};")
        lines.append(f"static const uint32_t {name}_off[{len(gl)}] = {{{', '.join(map(str, offs))}}};")
        rows = [", ".join(f"0x{b:02X}" for b in bits[i:i + 24]) for i in range(0, len(bits), 24)]
        lines.append(f"static const uint8_t {name}_bits[{len(bits)}] = {{\n    " + ",\n    ".join(rows) + "};")
        lines.append(f'static const op_font {name} = {{ {H}, "{esc}", {len(gl)}, {name}_adv, {name}_off, {name}_bits }};')
        lines.append("")
        print(f"{name}: {fname} {size}px -> {H} px high, {len(gl)} glyphs, {len(bits)} bytes")
    open(OUT, "w").write("\n".join(lines))
    print(f"-> {os.path.relpath(OUT, ROOT)} ({total} bytes of glyphs)")


if __name__ == "__main__":
    main()
