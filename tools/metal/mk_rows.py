# POCKET METAL: the fitted metal amps and pedals (tools/fit_amp.py, tools/fit_drive.py, docs/METAL.md) -> the engine's
# table rows for the PX_METAL build (engine/px_metal_amps.h, px_metal_drives.h, px_metal_drv_trim.h). The rows are in
# the same form as OpenPocket's own fitted rows (engine/px_dsp.c AV and DV): the same code runs them.
#   python3 tools/metal/mk_rows.py FIT_DIR
# FIT_DIR holds the fits' JSON, named after the rows below. The levels (px_metal_amp_lvl.h, px_metal_drv_db.h) come
# afterwards from tools/metal/level_metal.py.
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ENG = os.path.join(ROOT, "engine")
# (file, the row's name on the pedal, its enum in engine/px_dsp.h) in the enum's order
AMPS = [("recto", "RECTO", "PX_AMP_RECTO"), ("6505", "6505", "PX_AMP_6505"), ("IIIRED", "5153 RED", "PX_AMP_IIIRED"),
        ("XXX", "XXX", "PX_AMP_XXX"), ("SAVAGE", "SAVAGE", "PX_AMP_SAVAGE"), ("ROCKERVERB", "ROCKERVERB", "PX_AMP_ROCKER"),
        ("GH100", "GH100", "PX_AMP_GH100"), ("MIG50", "MIG 50", "PX_AMP_MIG50"), ("YERASOV", "YERASOV", "PX_AMP_YERASOV"),
        ("JVMOD2", "JVM OD2", "PX_AMP_JVM")]
DRIVES = [("PRECISION", "PRECISION", "PX_DRV_PRECISION"), ("DS1", "DS-1", "PX_DRV_DS1"), ("RAT", "RAT", "PX_DRV_RAT"),
          ("OS2", "OS-2", "PX_DRV_OS2"), ("UBERMETAL", "UBER METAL", "PX_DRV_UBER")]
HEAD = "/* GENERATED by tools/metal/mk_rows.py from the fits (docs/METAL.md): do not edit. PX_METAL builds only. */\n"


def f(x):
    s = "%.4g" % x
    if "e" not in s and "." not in s:
        s += ".0"
    return s + "f"


def amp_row(name, j):
    v, n = j["values"], j["stages"]
    g = lambda k: "{" + ", ".join(f(v["%s%d" % (k, i)]) if i < n else "0" for i in range(4)) + "}"
    rest = ", ".join(f(v[k]) for k in ("tight", "bright", "bright_db", "bass", "mid", "midq10", "treb", "rb", "rm", "rt",
                                         "scoop", "pres", "res", "res_db", "vf", "vdb", "sag100", "pw10"))
    a = j["after"]
    return ('  {"%s", %d,%d, %s, %s, %s, %s, %s},  /* %s; spectrum %.1f dB, dynamics %.1f dB */'
            % (name, n, j.get("hard", 0), g("g"), g("bias"), g("lp"), g("hp"), rest, j["capture"].replace(".nam", ""),
               a["val_ltas_db"], a["val_env_db"]))


def drv_row(name, j):
    v, roles = j["values"], j["roles"]
    L = "L%d(%s)" % (len(roles), ", ".join(roles))
    nums = lambda ks: ", ".join(f(v[k]) for k in ks)
    return ('    {"%s", %s, %s, %s, %s, %s},  /* %s; spectrum %.1f dB */'
            % (name, L, nums(("hp", "shelf", "lp", "mid", "mid_db", "mid_q10", "g0", "g1")), j["clip"], j["tm"],
               nums(("t0", "t1", "p2", "p2db", "blend", "bias", "gate")), j["capture"].replace(".nam", ""),
               j["after"]["val_ltas_db"]))


def load(d, fn, kind, start):
    """a fit's JSON; while a fit is missing (a first build), its start row as it is, with a warning"""
    p = os.path.join(d, fn + ".json")
    if os.path.exists(p):
        return json.load(open(p))
    print("warning: no fit %s: the row of %s stands in" % (p, start))
    sys.path.insert(0, os.path.join(ROOT, "tools"))
    after = {"val_ltas_db": 0.0, "val_env_db": 0.0}
    if kind == "amp":
        import fit_amp
        n, hard, v = fit_amp.table_row(start)
        return {"stages": n, "hard": hard, "capture": "(stand-in: %s)" % start, "after": after,
                "values": dict(zip(fit_amp.FIELDS, [float(x) for x in v]))}
    import fit_drive
    clip, tm, roles, np_, v = fit_drive.table_row(start)
    return {"roles": [fit_drive.ROLES[r] for r in roles[:np_]], "clip": fit_drive.CLIPS[clip], "tm": fit_drive.TMS[tm],
            "capture": "(stand-in: %s)" % start, "after": after, "values": dict(zip(fit_drive.FIELDS, [float(x) for x in v]))}


START = {"recto": "5150", "6505": "5150", "IIIRED": "5150", "XXX": "5150", "SAVAGE": "PRO MOD", "ROCKERVERB": "JCM2000",
         "GH100": "JCM900", "MIG50": "JCM900", "YERASOV": "5150", "JVMOD2": "JCM2000", "PRECISION": "TS9", "DS1": "M77 OD",
         "RAT": "M77 OD", "OS2": "M77 OD", "UBERMETAL": "SWEDE HM-2"}


def main():
    d = sys.argv[1] if len(sys.argv) > 1 else "."
    amps, drives, trims = [], [], []
    for fn, name, _ in AMPS:
        amps.append(amp_row(name, load(d, fn, "amp", START[fn])))
    for fn, name, _ in DRIVES:
        j = load(d, fn, "drv", START[fn])
        drives.append(drv_row(name, j))
        trims.append(f(j["values"]["trim"]))
    open(os.path.join(ENG, "px_metal_amps.h"), "w").write(HEAD + "\n".join(amps) + "\n")
    open(os.path.join(ENG, "px_metal_drives.h"), "w").write(HEAD + "\n".join(drives) + "\n")
    open(os.path.join(ENG, "px_metal_drv_trim.h"), "w").write(HEAD + "    " + ", ".join(trims) + ",\n")
    for p, n in (("px_metal_amp_lvl.h", len(AMPS)), ("px_metal_drv_db.h", len(DRIVES))):
        q = os.path.join(ENG, p)
        if not os.path.exists(q) or "GENERATED by tools/metal/level_metal.py" not in open(q).read():
            body = ("    {" + ", ".join(["-15.0f"] * 11) + "},\n") * n if "amp" in p else "    " + ", ".join(["-10.0f"] * n) + ",\n"
            open(q, "w").write("/* placeholders until tools/metal/level_metal.py runs */\n" + body)
    print("rows: %d amps, %d drives" % (len(amps), len(drives)))


if __name__ == "__main__":
    main()
