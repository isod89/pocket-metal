# POCKET METAL's levels (docs/METAL.md), the way OpenPocket's are made (tools/calib_levels.py, tools/level_presets.py):
# loudness = ITU-R BS.1770 of real DI guitar at the pedal's level.
#  1. each metal amp over its GAIN knob, into the 1x12: at noon at TARGET LUFS, +3 dB at 100 and -3 dB at 0
#     -> engine/px_metal_amp_lvl.h (rows of AMP_LVL)
#  2. each metal pedal, knobs at noon, in front of TWIN at noon: switching it on keeps the loudness -> px_metal_drv_db.h
#     (down to -40 dB: the fits' trims follow the captures' own levels, some much hotter than OpenPocket's pedals)
#  3. each factory sound's LEVEL so that it plays at TARGET LUFS -> firmware/apps/metal/mx_levels.h
#   python3 tools/metal/level_metal.py DI.wav [DI2.wav ...]
#   python3 tools/metal/level_metal.py --sounds DI.wav [...]   step 3 only: the amps' and pedals' levels kept
import os, re, subprocess, sys
import numpy as np
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
from calib_levels import lufs, ROOT, TARGET, RISE

ENG = os.path.join(ROOT, "engine")
APP = os.path.join(ROOT, "firmware", "apps", "metal")
BUILD = os.path.join(ROOT, "build")
CHAIN, RENDER = os.path.join(BUILD, "lvl_chain_metal"), os.path.join(BUILD, "mx_render")
DEFS = ["-DPX_NO_NAM=1", "-DPX_METAL=1", "-DPX_SR=44100.0f", "-DPX_OVERSAMPLE=4"]
N_OP_AMPS, N_METAL_AMPS = 8, 10                     # OpenPocket's fitted amps first, then the metal ones (px_dsp.h)
N_OP_DRV, N_METAL_DRV = 4, 5
B_DRV, B_AMP, B_CAB = 4, 5, 6
NFACT = int(re.search(r"#define MX_NFACT (\d+)", open(os.path.join(APP, "mx_presets.h")).read()).group(1))
HEAD = "/* GENERATED by tools/metal/level_metal.py: do not edit. PX_METAL builds only. */\n"


def build():
    os.makedirs(BUILD, exist_ok=True)
    subprocess.run(["cc", "-O2", *DEFS, "-I" + ENG, os.path.join(ROOT, "tests", "engine", "chain.c"),
                    os.path.join(ENG, "px_dsp.c"), os.path.join(ROOT, "firmware", "px_math.c"), "-lm", "-o", CHAIN], check=True)
    subprocess.run(["cc", "-O2", *DEFS, "-I" + ENG, "-I" + APP, os.path.join(ROOT, "tests", "metal", "mx_render.c"),
                    os.path.join(APP, "mx_engine.c"), os.path.join(ROOT, "firmware", "px_math.c"), "-lm", "-o", RENDER], check=True)


def loud(dis, blocks):
    args = []
    for b, t, k in blocks:
        args += [str(b), str(t)] + [str(v) for v in k]
    out = os.path.join(BUILD, "lvlm.f32")
    ls = []
    for d in dis:
        subprocess.run([CHAIN, d, out] + args, check=True)
        ls.append(lufs(np.fromfile(out, np.float32).astype(np.float64)))
    return float(np.mean(ls))


def loud_preset(dis, k):
    out = os.path.join(BUILD, "lvlm.f32")
    ls, pk = [], -99.0
    for d in dis:
        r = subprocess.run([RENDER, d, str(k), out], check=True, capture_output=True, text=True).stdout.split()
        pk = max(pk, float(r[-2]))
        ls.append(lufs(np.fromfile(out, np.float32).astype(np.float64)))
    return " ".join(r[:-2]), float(np.mean(ls)), pk


def write_amps(rows):
    open(os.path.join(ENG, "px_metal_amp_lvl.h"), "w").write(
        HEAD + "".join("    {" + ", ".join("%.2ff" % v for v in r) + "},\n" for r in rows))


def write_drv(v):
    open(os.path.join(ENG, "px_metal_drv_db.h"), "w").write(HEAD + "    " + ", ".join("%.2ff" % x for x in v) + ",\n")


def write_presets(lv):
    open(os.path.join(APP, "mx_levels.h"), "w").write(
        "/* GENERATED by tools/metal/level_metal.py: do not edit. Each factory sound's LEVEL (0.3 dB a step, 50 = 0 dB),\n"
        " * so that it plays at %.0f LUFS on DI guitar, as OpenPocket's sounds do. */\n" % TARGET +
        "static const uint8_t MX_LVL[MX_NFACT] = {" + ", ".join(str(v) for v in lv) + "};\n")


def sounds(dis):
    lv = [50] * NFACT                                 # 3. the sounds
    write_presets(lv); build()
    for it in range(2):
        for k in range(NFACT):
            name, l, pk = loud_preset(dis, k)
            lv[k] = int(np.clip(round(lv[k] + (TARGET - l) / 0.3), 0, 100))
            if it:
                print("%2d %-14s %6.1f LUFS  peak %5.1f dB  LEVEL %d" % (k + 1, name, l, pk, lv[k]), flush=True)
        write_presets(lv); build()
    worst = max(abs(loud_preset(dis, k)[1] - TARGET) for k in range(NFACT))
    print("largest remaining difference: %.2f dB" % worst)


def main():
    dis = sys.argv[1:]
    only = "--sounds" in dis
    dis = [d for d in dis if d != "--sounds"]
    if not dis:
        sys.exit("usage: level_metal.py [--sounds] DI.wav [DI2.wav ...]")
    if only:
        return sounds(dis)
    noon = [50] * 5
    cab0 = (B_CAB, 0, noon)
    amps = [[0.0] * 11 for _ in range(N_METAL_AMPS)]
    drv = [0.0] * N_METAL_DRV
    write_amps(amps); write_drv(drv); write_presets([0] * NFACT); build()
    for a in range(N_METAL_AMPS):                    # 1. the amps
        for i, g in enumerate(range(0, 101, 10)):
            amps[a][i] = round(TARGET + RISE * (g / 100.0 - 0.5) - loud(dis, [(B_AMP, N_OP_AMPS + a, [g, 50, 50, 50, 50]), cab0]), 2)
        print("amp %d:" % a, " ".join("%+.1f" % v for v in amps[a]), flush=True)
    write_amps(amps); build()
    amp = (B_AMP, 0, noon)                            # 2. the pedals, in front of TWIN at noon
    ref = loud(dis, [amp, cab0])
    for it in range(3):
        for d in range(N_METAL_DRV):
            l = loud(dis, [amp, cab0, (B_DRV, N_OP_DRV + d, noon)])
            drv[d] = round(float(np.clip(drv[d] + ref - l, -40, 15)), 2)
        print(it, "drives", drv, flush=True)
        write_drv(drv); build()
    sounds(dis)


if __name__ == "__main__":
    main()
